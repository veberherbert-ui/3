/* Заголовки безопасности для собранного приложения.

   Приложение целиком статическое и никуда не ходит по сети, так что
   красть у него нечего и ломать через сервер нечего — сервера нет.
   Но два заголовка нужны даже такому.

   Первый — запрет встраивания. Без него чужая страница может открыть
   дневник в рамке внутри себя, положить сверху прозрачные кнопки
   и получить нажатия человека на своих условиях. Никакой хитрости
   для этого не нужно.

   Второй — политика содержимого. Она не защищает от того, что уже есть
   в сборке, зато отвечает на вопрос «а что, если однажды в приложение
   попадёт чужой код»: через испорченную зависимость, подменённую
   раздачу, что угодно. С политикой такой код не сможет ни загрузиться
   с чужого адреса, ни отправить наружу ни байта — а дневник это
   единственное, что у приложения есть ценного.

   Встроенный сценарий (экран поломки в index.html) остаётся встроенным
   намеренно: он обязан работать, когда не загрузилось ничего другого.
   Поэтому здесь считается его отпечаток и вписывается в политику —
   разрешён ровно он, а не «любые встроенные сценарии».

   Запуск: после vite build, см. npm run build */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";

const HTML = "dist/index.html";
const OUT = "dist/_headers";

if (!existsSync(HTML)) {
  console.error("✗ Нет dist/index.html — сборка не выполнялась");
  process.exit(1);
}

const html = readFileSync(HTML, "utf8");

/* Отпечатки встроенных сценариев: только те, что без src. */
const hashes = [];
for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
  hashes.push(`'sha256-${createHash("sha256").update(m[1], "utf8").digest("base64")}'`);
}
if (!hashes.length) {
  console.error("✗ Во встроенной странице не нашлось ни одного сценария — что-то не так со сборкой");
  process.exit(1);
}

const csp = [
  /* всё своё и ничего чужого */
  "default-src 'self'",
  `script-src 'self' ${hashes.join(" ")}`,
  /* Стили в разметке (style={{…}}) — основной способ раскраски в этом
     приложении, и браузер считает их встроенными. Отказаться от них
     значило бы переписать оформление целиком; риск при этом невелик:
     стилем данные наружу не отправить. */
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  /* data: обязателен: мелкие куски шрифтов сборщик вшивает прямо в стили,
     а не кладёт файлами. Без этой строки половина начертаний не грузится —
     поймано проверкой, а не глазами. Опасности в этом нет: шрифтом
     данные наружу не отправить. */
  "font-src 'self' data:",
  /* Главная строчка: приложение не разговаривает ни с кем, кроме своего
     же адреса. Чужой код, окажись он внутри, не сможет отправить дневник
     наружу — ему просто не дадут открыть соединение. */
  "connect-src 'self'",
  "worker-src 'self'",
  "manifest-src 'self'",
  /* blob: — сигнал окончания отдыха: звук собирается в памяти и играется
     оттуда, файлом он никогда не был. Тоже поймано проверкой. */
  "media-src 'self' data: blob:",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  /* никаких рамок: ни нас в чужую страницу, ни чужую в нас */
  "frame-ancestors 'none'",
  "frame-src 'none'",
].join("; ");

const body = `# Создаётся при сборке (tools/headers.mjs). Руками не править.
#
# Хешированные файлы сборки можно кешировать навсегда — при изменении
# у них меняется имя.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Обслуживающий скрипт и страница обязаны проверяться каждый раз,
# иначе обновление приложения не доедет до уже установленных телефонов.
/sw.js
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
/manifest.webmanifest
  Cache-Control: no-cache

/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  # Ничего из этого приложению не нужно — и пусть браузер это знает.
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin
`;

writeFileSync(OUT, body);
console.log(`✓ Заголовки записаны: политика содержимого, запрет встраивания, ${hashes.length} отпечаток встроенного сценария.`);
