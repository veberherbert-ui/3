/* Палитра приложения. Тёмная тема с «меловым» текстом — читается в зале
   при любом свете.

   У насыщенных цветов две роли, и для них нужны разные оттенки.

   Как заливка кнопки цвет должен быть достаточно тёмным, чтобы белая
   надпись на нём читалась. Как текст на тёмном фоне — наоборот, достаточно
   светлым. Один оттенок не может и то и другое: исходный красный давал
   белому тексту контраст 4.21, а сам на карточке — 2.86 при норме 4.5.

   Поэтому пары: red для заливок, redText для надписей. Все сочетания
   проверены и проходят норму AA. Пересчитать после правки можно формулой
   WCAG, порядок описан в docs/interface.md. */

export const C = {
  bg: "#15171B",
  surface: "#1D2024",
  surfaceHi: "#262A2F",
  line: "#3A3F46",

  chalk: "#EDEAE3", // основной текст, 12.0 на карточке
  dim: "#B7B5B1", // второстепенный, 7.0 — было 5.1 и на мелком размере не читалось

  /* заливки: белая надпись на них даёт 4.6 */
  red: "#B74137",
  blue: "#3E6B8A",
  moss: "#47734C",
  mustard: "#C9A227", // на нём пишем тёмным, bg даёт 7.4

  /* те же цвета для текста на тёмном фоне: 4.6–4.7 */
  redText: "#D37A73",
  blueText: "#7696AC",
  mossText: "#789B7D",
};

/* Цвета мышечных групп для столбиков объёма.

   Шесть оттенков, различимых на тёмном фоне и друг от друга. Взяты
   в одной насыщенности, чтобы ни одна группа не выглядела важнее прочих:
   столбик показывает распределение, а не приоритет. */
export const GROUP_COLOR = {
  Грудь: "#C05A4E",
  Спина: "#4E7FA8",
  Плечи: "#C9A227",
  Руки: "#7E6BA8",
  Ноги: "#4F8A63",
  Кор: "#9C8468",
};

/** Цвет блина по весу — как в зале: тяжёлое красное, лёгкое зелёное. */
export const plateColor = (kg) =>
  kg >= 70 ? C.red : kg >= 45 ? C.blue : kg >= 25 ? C.mustard : kg >= 10 ? C.moss : C.dim;
