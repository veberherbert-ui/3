export const REST_MIN = 15;
export const REST_MAX = 600;
export const REST_STEP = 15;

const clamp = (v) => Math.min(REST_MAX, Math.max(REST_MIN, v));

/** Округление до шага, чтобы не появлялись значения вроде 97 секунд */
const round = (v) => Math.round(v / REST_STEP) * REST_STEP;

/**
 * Время отдыха для упражнения, секунд.
 * @param {string} name
 * @param {Record<string,number>} [overrides] правки пользователя
 */
export function restFor(name, overrides) {
  const own = overrides?.[name];
  if (own) return clamp(own);
  if (OVERRIDE[name]) return OVERRIDE[name];

  const info = EXDB[name];
  if (!info) return 90;

  const base = BY_MUSCLE[info.m] ?? 90;
  return clamp(round(base + (BY_EQUIPMENT[info.eq] ?? 0)));
}

/** «2:30» или «45 сек» — короткая подпись для кнопок и списков */
export const fmtRest = (sec) => (sec >= 60 ? `${Math.floor(sec / 60)}:${String(sec % 60).padStart(2, "0")}` : `${sec} сек`);

export const stepRest = (sec, dir) => clamp(round(sec + dir * REST_STEP));
