import { isPair } from "../data/exercises.js";

/* Починка записей, сделанных до появления новых правил счёта.

   Признак «две гантели» появился позже самих тренировок, а хранится он
   в записи — чтобы старые данные не менялись задним числом. Побочный
   эффект оказался хуже проблемы: одно и то же упражнение в мае считалось
   ×1, в августе ×2, и на графике тоннажа возникала ступенька, которой
   не было в зале.

   Здесь это доводится до общего знаменателя. Правка безопасна: вес
   в поле всегда писали за одну гантель — гантельный жим на 12 кг общего
   веса не бывает, — значит недостающий множитель просто не был применён. */
export function fillPairFlags(workouts) {
  let touched = 0;
  const next = (workouts || []).map((w) => {
    let changed = false;
    const exercises = w.exercises.map((e) => {
      if (e.pair !== undefined) return e;
      const pair = isPair(e.name);
      /* Тоннаж меняется только там, где упражнение действительно парное;
         остальным просто дописываем флаг, чтобы больше не гадать. */
      if (pair) changed = true;
      return { ...e, pair };
    });
    if (changed) touched++;
    return { ...w, exercises };
  });
  return { workouts: next, touched };
}
