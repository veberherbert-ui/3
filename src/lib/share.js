/* Поделиться приложением.

   Ссылку на приложение неоткуда взять изнутри самого приложения: у
   установленного нет строки адреса, а во вкладке она есть, но лезть
   за ней и выделять руками — не то, что делают, когда телефон уже
   протянут другому человеку.

   Здесь два способа отдать ссылку, и у каждого своя роль.

   «Поделиться» — системное меню: телеграм, почта, сообщения. Годится,
   когда человек далеко. Но у этого пути есть подвох, о котором стоит
   помнить: ссылка, открытая из мессенджера, попадёт во встроенное окно,
   а поставить приложение оттуда нельзя (см. lib/install.js).

   Код — для человека рядом. Наведённая камера открывает ссылку в
   основном браузере телефона, а не во встроенном окне, то есть сразу
   там, где установка работает. Для «переставить жене» это и есть
   короткий путь. */

/** Адрес приложения без служебных хвостов вроде ?fresh=. */
export const appUrl = () => window.location.origin + window.location.pathname;

const TITLE = "Железный дневник";
const TEXT = "Дневник силовых тренировок. Работает без сети, ничего не просит и никуда не отправляет.";

/**
 * Отдать ссылку тем способом, который есть на этом телефоне.
 * @returns {Promise<"shared"|"cancelled"|"copied"|"failed">}
 */
export async function shareApp() {
  const url = appUrl();

  if (navigator.share) {
    try {
      await navigator.share({ title: TITLE, text: TEXT, url });
      return "shared";
    } catch (e) {
      /* закрыл меню — это не ошибка, и подсовывать вместо него буфер обмена
         не надо: человек только что отказался */
      if (e?.name === "AbortError") return "cancelled";
    }
  }

  try {
    await navigator.clipboard.writeText(url);
    return "copied";
  } catch {
    return "failed";
  }
}

/** Есть ли на этом устройстве системное «Поделиться». */
export const canShare = () => typeof navigator !== "undefined" && !!navigator.share;
