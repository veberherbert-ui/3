export const helpfulNote = (exName, condIds) => {
  for (const id of condIds || []) {
    const n = HELPFUL[id]?.[exName];
    if (n) return { id, name: CONDITION_BY_ID[id]?.name || id, note: n };
  }
  return null;
};

/** Степень риска упражнения при состоянии: 0 — нет данных о проблемах. */
export const riskOf = (exName, condId) => RISKS[exName]?.[condId]?.[0] ?? 0;

/** Пояснение, почему это упражнение проблемно при этом состоянии. */
export const riskNote = (exName, condId) => RISKS[exName]?.[condId]?.[1] || null;

/** Худшая степень риска упражнения по списку выбранных состояний. */
export function worstRisk(exName, condIds) {
  let worst = 0;
  (condIds || []).forEach((id) => {
    const r = riskOf(exName, id);
    if (r > worst) worst = r;
  });
  return worst;
}

/** Все сработавшие метки: [{ id, name, level, note }] — от худшей к лёгкой. */
export function risksFor(exName, condIds) {
  return (condIds || [])
    .map((id) => ({ id, name: CONDITION_BY_ID[id]?.name || id, level: riskOf(exName, id), note: riskNote(exName, id) }))
    .filter((r) => r.level > 0)
    .sort((a, b) => b.level - a.level);
}
