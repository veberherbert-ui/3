export const isPair = (n) => {
  const i = EXDB[n];
  if (!i || i.uni) return false;
  if (i.eq === "Гантели") return true;
  /* Кроссовер — это два блока по определению: рукоять в каждой руке,
     на каждой стороне свой стек. Остальные блоки и тренажёры бывают
     и с одним, и с двумя — там решает зал, а не название. */
  return /^Кроссовер/.test(n);
};

