/* Метки упражнения в тренировке.

   Цифры не помнят, как оно было. Восемь по шестьдесят в отказ с последним
   повторением на читинге и восемь по шестьдесят в запас — одна и та же
   строчка в журнале, а через месяц разница важнее самих цифр: по ней видно,
   почему на следующей тренировке вес не пошёл.

   Меток намеренно мало. Длинный список никто не заполняет, а половина
   вариантов оказывается неотличима друг от друга. Здесь только то, что
   реально меняет прочтение записи. */

export const TAGS = [
  { id: "fail", label: "отказ", hint: "последнее повторение не дожал" },
  { id: "cheat", label: "читинг", hint: "техника поехала, помогал корпусом" },
  { id: "drop", label: "дроп-сет", hint: "сбрасывал вес не отдыхая" },
  { id: "pause", label: "с паузой", hint: "остановка в нижней точке" },
  { id: "partial", label: "частичные", hint: "короткая амплитуда" },
  { id: "easy", label: "был запас", hint: "мог ещё, можно добавлять" },
  { id: "pain", label: "болело", hint: "неприятные ощущения в суставе", warn: true },
];

export const TAG_BY_ID = Object.fromEntries(TAGS.map((t) => [t.id, t]));

/** Читаемая строка меток: «отказ · читинг». */
export const tagLine = (ids) =>
  (ids || []).map((id) => TAG_BY_ID[id]?.label).filter(Boolean).join(" · ");
